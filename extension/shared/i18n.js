// hardcoded literal. The SINGLE source of truth for message text is
// extension/_locales/en/messages.json (the Chrome MV3 message catalogue);
// the manifest's default_locale points at it.
//
// Resolution order:
//   1. chrome.i18n.getMessage — present in every extension context (pages,
//      service worker, content scripts, workers). Adding a second locale is
//      ONLY a new extension/_locales/<lang>/messages.json catalogue; Chrome
//      selects it from the browser language with ZERO code change.
//   2. The embedded DEFAULT catalogue below — a byte-identical synced copy of
//      _locales/en/messages.json, regenerated by scripts/sync-i18n.mjs. It is
//      the fallback for contexts with no chrome.i18n — chiefly the docs/
//      component gallery, which loads these components from a plain web page
//      and must render IDENTICALLY after migration (the gallery drift guard).
//
// A missing key returns the key itself: a migration gap is loud, never a
// silent blank.

