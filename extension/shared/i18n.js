/** Apply positional $1..$9 substitutions (chrome.i18n parity for the
 * fallback path; the extension path gets them natively). */
function substitute(message, subs) {
  if (!subs || subs.length === 0) return message;
  return String(message).replace(/\$([1-9])/g, (m, n) => {
    const v = subs[Number(n) - 1];
    return v === undefined || v === null ? m : String(v);
  });
}

/** Resolve a catalogue key to user-visible text.
 * `t("settings_nav_providers")` or `t("origin_turn_off", origin)`. */
export function t(key, ...subs) {
  const args = subs.length === 1 && Array.isArray(subs[0]) ? subs[0] : subs;
  try {
    if (typeof chrome !== "undefined" && chrome?.i18n?.getMessage) {
      const v = chrome.i18n.getMessage(key, args.length ? args : undefined);
      if (v) return v;
    }
  } catch {
    /* fall through to the default catalogue */
  }
  const message = I18N_DEFAULT_CATALOGUE[key];
  if (message === undefined) return key; // loud, never silent
  return args.length ? substitute(message, args) : message;
}

/** Hydrate static HTML: fill `data-i18n` text content and `data-i18n-attr`
 * attributes from the catalogue. Attribute form:
 * `data-i18n-attr="aria-label:key;title:key2"` (attribute:key pairs).
 * Elements keep their English text in the markup as the no-JS fallback; the
 * catalogue value is byte-identical so rendering is unchanged. */
export function hydrateI18n(root = document) {
  if (!root?.querySelectorAll) return;
  for (const el of root.querySelectorAll("[data-i18n]")) {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  }
  for (const el of root.querySelectorAll("[data-i18n-attr]")) {
    const spec = el.getAttribute("data-i18n-attr") || "";
    for (const pair of spec.split(";")) {
      const idx = pair.indexOf(":");
      if (idx <= 0) continue;
      const attr = pair.slice(0, idx).trim();
      const key = pair.slice(idx + 1).trim();
      if (attr && key) el.setAttribute(attr, t(key));
    }
  }
}
